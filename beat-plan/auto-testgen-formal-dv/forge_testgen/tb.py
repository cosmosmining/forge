"""Self-checking SystemVerilog testbench emitters.

Stimulus and expected results are computed in Python (golden model) and
written to hex files; the testbench drives the DUT, compares in simulation
(!== so X/Z count as mismatches) and also dumps what it saw so the Python
side re-checks independently.  Drive at negedge, sample at posedge: no
TB/DUT races regardless of how the DUT is written.
"""


def pack(fields, vec):
    """Concatenate fields LSB-first (field 0 lowest bits) -> int."""
    out, off = 0, 0
    for f in fields:
        out |= f.encode(vec[f.name]) << off
        off += f.total_bits
    return out


def unpack(fields, bits):
    out, off = {}, 0
    for f in fields:
        out[f.name] = f.decode((bits >> off) & ((1 << f.total_bits) - 1))
        off += f.total_bits
    return out


def total_bits(fields):
    return sum(f.total_bits for f in fields)


def write_hex(path, values, width):
    digits = max(1, (width + 3) // 4)
    with open(path, "w") as fh:
        for v in values:
            fh.write("%0*x\n" % (digits, v & ((1 << width) - 1)))


def read_hex(path):
    vals = []
    with open(path) as fh:
        for line in fh:
            s = line.strip()
            if not s:
                continue
            if any(c in s.lower() for c in "xz"):
                vals.append(None)  # X/Z seen
            else:
                vals.append(int(s, 16))
    return vals


def _port_slices(fields, port_of, bus):
    """[(port, 'bus[hi:lo]')] for each field."""
    out, off = [], 0
    for f in fields:
        out.append((port_of(f), "%s[%d:%d]" % (bus, off + f.total_bits - 1, off)))
        off += f.total_bits
    return out


def comb_tb(top, in_fields, out_fields, n_vectors, port_of=lambda f: f.port, extra_outputs=()):
    """Testbench for a combinational block: apply vector, wait, compare."""
    iw, ow = total_bits(in_fields), total_bits(out_fields)
    conns = ["    .%s(cur%s)" % (p, s[3:]) for p, s in _port_slices(in_fields, port_of, "cur")]
    conns += ["    .%s(got%s)" % (p, s[3:]) for p, s in _port_slices(out_fields, port_of, "got")]
    conns += ["    .%s()" % p for p in extra_outputs]
    return """`timescale 1ns/1ps
// Generated by forge_testgen -- combinational self-checking testbench.
module tb;
  localparam N = %(n)d;
  reg  [%(iw1)d:0] stim [0:N-1];
  reg  [%(ow1)d:0] expv [0:N-1];
  reg  [%(iw1)d:0] cur;
  wire [%(ow1)d:0] got;
  integer i, errors, fd;
  %(top)s dut (
%(conns)s
  );
  initial begin
    $readmemh("stim.hex", stim);
    $readmemh("exp.hex", expv);
    fd = $fopen("got.hex", "w");
    errors = 0;
    for (i = 0; i < N; i = i + 1) begin
      cur = stim[i];
      #1;
      $fwrite(fd, "%%h\\n", got);
      if (got !== expv[i]) begin
        errors = errors + 1;
        if (errors <= 10) $display("MISMATCH vec=%%0d got=%%h exp=%%h", i, got, expv[i]);
      end
      #1;
    end
    $fclose(fd);
    $display("RESULT errors=%%0d vectors=%%0d", errors, N);
    $finish;
  end
endmodule
""" % {"n": n_vectors, "iw1": iw - 1, "ow1": ow - 1, "top": top, "conns": ",\n".join(conns)}


def stream_tb(top, in_fields, out_fields, n_in, n_out, n_rdy, proto, max_latency,
              drain=24, rst_cycles=3, max_cycles=None):
    cap = int(proto.get("capacity") or 0)
    max_stall = int(proto.get("max_stall", max_latency + cap + 1))
    below_cap = 1 if (proto.get("accepts_below_capacity") and cap and proto.get("in_ready")) else 0
    """Testbench for a valid/ready stream block (one output per input, in order).

    proto: dict with keys clk, rst, rst_active ('high'|'low'), in_valid,
    in_ready (or None), out_valid, out_ready (or None).
    """
    iw, ow = total_bits(in_fields), total_bits(out_fields)
    if max_cycles is None:
        max_cycles = 64 + n_in * 300 + n_rdy
    conns = ["    .%s(clk)" % proto["clk"]]
    conns.append("    .%s(%s)" % (proto["rst"], "rst_i" if proto.get("rst_active", "high") == "high"
                                  else "~rst_i"))
    conns.append("    .%s(in_valid)" % proto["in_valid"])
    if proto.get("in_ready"):
        conns.append("    .%s(in_ready)" % proto["in_ready"])
    conns.append("    .%s(out_valid)" % proto["out_valid"])
    if proto.get("out_ready"):
        conns.append("    .%s(out_ready)" % proto["out_ready"])
    conns += ["    .%s(in_data%s)" % (p, s[7:]) for p, s in _port_slices(in_fields, lambda f: f.port, "in_data")]
    conns += ["    .%s(out_data%s)" % (p, s[8:]) for p, s in _port_slices(out_fields, lambda f: f.port, "out_data")]
    in_ready_decl = "wire in_ready;" if proto.get("in_ready") else "wire in_ready = 1'b1;"
    junk_reps = iw // 32 + 1
    return """`timescale 1ns/1ps
// Generated by forge_testgen -- valid/ready stream self-checking testbench.
module tb;
  localparam N = %(n_in)d, M = %(n_out)d, R = %(n_rdy)d;
  localparam MAXLAT = %(maxlat)d, DRAIN = %(drain)d, MAXCYC = %(maxcyc)d;
  localparam MAXSTALL = %(maxstall)d, CAP = %(cap)d, BELOWCAP = %(belowcap)d;
  reg clk = 1'b0;
  always #5 clk = ~clk;
  reg rst_i = 1'b1;
  reg in_valid = 1'b0;
  reg [%(iw1)d:0] in_data = 0;
  %(in_ready_decl)s
  wire out_valid;
  reg out_ready = 1'b0;
  wire [%(ow1)d:0] out_data;
  %(top)s dut (
%(conns)s
  );
  reg [%(iw1)d:0] stim [0:N-1];
  reg [7:0]       gap  [0:N-1];
  reg [0:0]       rdy  [0:R-1];
  reg [%(ow1)d:0] expv [0:M-1];
  integer in_idx = 0, out_idx = 0, cyc = 0, errors = 0, gap_left = 0, fd;
  integer stall = 0, drain_cnt = 0, inflight = 0, istall = 0;
  integer cov_bp = 0, cov_install = 0, cov_b2b_in = 0, cov_b2b_out = 0, max_inflight = 0;
  reg started = 1'b0, prev_bp = 1'b0, prev_acc = 1'b0, prev_out = 1'b0, finishing = 1'b0;
  reg [%(ow1)d:0] prev_data = 0;
  reg [31:0] junk = 32'h1234_5678;
  reg acc_now, out_now;

  task finish_run;
    begin
      $fclose(fd);
      $display("COV bp=%%0d install=%%0d b2b_in=%%0d b2b_out=%%0d max_inflight=%%0d",
               cov_bp, cov_install, cov_b2b_in, cov_b2b_out, max_inflight);
      $display("RESULT errors=%%0d in=%%0d out=%%0d expected=%%0d cycles=%%0d", errors, in_idx, out_idx, M, cyc);
      $finish;
    end
  endtask

  initial begin
    $readmemh("stim.hex", stim);
    $readmemh("gap.hex", gap);
    $readmemh("rdy.hex", rdy);
    $readmemh("exp.hex", expv);
    fd = $fopen("got.hex", "w");
    repeat (%(rst)d) @(posedge clk);
    @(negedge clk);
    rst_i = 1'b0;
    gap_left = gap[0];
    started = 1'b1;
  end

  // ---- sample at posedge ------------------------------------------------
  always @(posedge clk) if (started && !finishing) begin
    cyc = cyc + 1;
    acc_now = in_valid && in_ready;
    out_now = out_valid && out_ready;
    if (out_valid !== 1'b0 && out_valid !== 1'b1) begin
      errors = errors + 1; $display("XPROP cyc=%%0d out_valid is X/Z", cyc);
    end
    if (in_ready !== 1'b0 && in_ready !== 1'b1) begin
      errors = errors + 1; $display("XPROP cyc=%%0d in_ready is X/Z", cyc);
    end
    if (in_valid && !in_ready && out_ready) istall = istall + 1;
    else istall = 0;
    if (istall > MAXSTALL) begin
      errors = errors + 1;
      $display("STALL cyc=%%0d input not accepted for %%0d cycles with out_ready high", cyc, istall);
      finishing = 1'b1;
      finish_run;
    end
    if (BELOWCAP && in_valid && !in_ready && (in_idx - out_idx) < CAP) begin
      errors = errors + 1;
      $display("PROTO cyc=%%0d input refused with %%0d of %%0d in flight", cyc, in_idx - out_idx, CAP);
    end
    if (prev_bp) begin
      if (out_valid !== 1'b1) begin
        errors = errors + 1; $display("PROTO cyc=%%0d out_valid dropped while stalled", cyc);
      end else if (out_data !== prev_data) begin
        errors = errors + 1; $display("PROTO cyc=%%0d out_data changed while stalled", cyc);
      end
    end
    if (acc_now) begin
      if (prev_acc) cov_b2b_in = cov_b2b_in + 1;
      in_idx = in_idx + 1;
    end
    if (in_valid && !in_ready) cov_install = cov_install + 1;
    if (out_now) begin
      if (out_idx >= M) begin
        errors = errors + 1; $display("EXTRA cyc=%%0d unexpected output %%h", cyc, out_data);
      end else begin
        $fwrite(fd, "%%h\\n", out_data);
        if (out_data !== expv[out_idx]) begin
          errors = errors + 1;
          if (errors <= 10) $display("MISMATCH txn=%%0d got=%%h exp=%%h cyc=%%0d", out_idx, out_data, expv[out_idx], cyc);
        end
      end
      if (out_idx + 1 > in_idx) begin
        errors = errors + 1; $display("PROTO cyc=%%0d output %%0d before its input was accepted", cyc, out_idx);
      end
      if (prev_out) cov_b2b_out = cov_b2b_out + 1;
      out_idx = out_idx + 1;
      stall = 0;
    end else if (out_ready && in_idx > out_idx) begin
      stall = stall + 1;
      if (stall > MAXLAT) begin
        errors = errors + 1;
        $display("TIMEOUT txn=%%0d no output for %%0d cycles with out_ready high", out_idx, stall);
        finishing = 1'b1;
        finish_run;
      end
    end
    if (out_valid && !out_ready) cov_bp = cov_bp + 1;
    inflight = in_idx - out_idx;
    if (inflight > max_inflight) max_inflight = inflight;
    prev_bp = out_valid && !out_ready;
    prev_data = out_data;
    prev_acc = acc_now;
    prev_out = out_now;
    if (in_idx >= N && out_idx >= M) begin
      drain_cnt = drain_cnt + 1;
      if (drain_cnt > DRAIN) begin finishing = 1'b1; finish_run; end
    end
    if (cyc > MAXCYC) begin
      errors = errors + 1;
      $display("TIMEOUT global cycle limit in=%%0d out=%%0d", in_idx, out_idx);
      finishing = 1'b1;
      finish_run;
    end
  end

  // ---- drive at negedge -------------------------------------------------
  always @(negedge clk) if (started && !finishing) begin
    junk = junk * 32'd1103515245 + 32'd12345;
    out_ready = (in_idx >= N && out_idx >= M) ? 1'b1 : rdy[cyc %% R];
    if (in_idx < N) begin
      if (in_valid && !prev_acc) begin
        in_valid = 1'b1;               // hold until accepted (valid/ready rule)
      end else begin
        if (prev_acc) gap_left = gap[in_idx];
        if (gap_left > 0) begin
          in_valid = 1'b0;
          in_data = {%(junk_reps)d{junk}};  // junk while idle: catches capture-without-valid
          gap_left = gap_left - 1;
        end else begin
          in_valid = 1'b1;
          in_data = stim[in_idx];
        end
      end
    end else begin
      in_valid = 1'b0;
      in_data = {%(junk_reps)d{junk}};
    end
  end
endmodule
""" % {"n_in": n_in, "n_out": n_out, "n_rdy": n_rdy, "maxlat": max_latency, "drain": drain,
       "maxcyc": max_cycles, "iw1": iw - 1, "ow1": ow - 1, "top": top,
       "conns": ",\n".join(conns), "in_ready_decl": in_ready_decl, "rst": rst_cycles,
       "junk_reps": junk_reps, "maxstall": max_stall, "cap": cap, "belowcap": below_cap}
