"""Human-readable summaries.

Every number printed here is copied from a report.json / mutation.json written
by the tool in the same run, and is labeled with its kind, following Forge's
reporting rule:  measured = a tool printed it (file named);  derived =
arithmetic on measured numbers (formula given);  not yet = not run.
"""

import json
import os
import time


def block_summary_text(r):
    b = r["block"]
    lines = ["== %s (%s) verdict: %s" % (b["name"], b["kind"], r["verdict"])]
    if r.get("spec_vs_rtl"):
        for i in r["spec_vs_rtl"]:
            lines.append("   spec/rtl: %s" % i)
    if r["verdict"] == "SPEC-ERROR":
        return "\n".join(lines)
    lines.append("   tests: %s" % r.get("tests"))
    cov = r.get("coverage", {})
    lines.append("   coverage: %s/%s bins hit (%s%%), %s excluded as proven unreachable, holes: %s" % (
        cov.get("bins_hit"), cov.get("bins_considered"), cov.get("coverage_pct"),
        cov.get("bins_excluded_unreachable"), cov.get("holes")))
    sims = r.get("simulation", {})
    bad = {k: v for k, v in sims.items() if not v["ok"]}
    lines.append("   simulation: %d runs, %d failing %s" % (len(sims), len(bad),
                                                          {k: v["messages"][:2] for k, v in bad.items()}))
    fv = r.get("formal")
    if fv:
        lines.append("   formal: %s %s (%.1fs)" % (fv["kind"], fv["verdict"], fv.get("seconds", 0)))
        if fv.get("failed"):
            lines.append("     failed: %s" % fv["failed"])
        if fv.get("cex"):
            lines.append("     cex replay: %s" % {k: v for k, v in fv["cex"].items() if k != "log"})
        if "covers_reached" in fv:
            lines.append("     covers reached: %s unreached: %s" % (fv["covers_reached"],
                                                                  fv["covers_unreached"]))
    lines.append("   translator self-check mismatches: %s" % r.get("translator_selfcheck_mismatches"))
    lines.append("   wall time: %ss" % r.get("seconds"))
    return "\n".join(lines)


def mutation_summary_text(m):
    s = m["summary"]
    lines = ["== mutation campaign: %s" % m["block"]]
    for k in ("mutants_total", "stillborn", "valid", "killed_by_sim", "killed_by_formal",
              "killed_any", "proven_equivalent", "bounded_equivalent",
              "spec_conformant_behavior_change", "survived", "formal_cex_not_confirmed_by_replay"):
        lines.append("   %-34s %s" % (k, s.get(k)))
    for k in ("sim_kill_rate", "formal_kill_rate", "combined_kill_rate",
              "directed_only_kill_rate", "random_only_kill_rate", "closure_only_kill_rate"):
        if k in s:
            lines.append("   %-34s %s" % (k, s[k]))
    if m.get("survivors"):
        lines.append("   survivors (not proven equivalent):")
        for sv in m["survivors"][:10]:
            lines.append("     %s" % sv)
    if m.get("conformant"):
        lines.append("   spec-conformant behavior changes:")
        for sv in m["conformant"][:10]:
            lines.append("     %s" % sv)
    return "\n".join(lines)


def _rel(path, root):
    return os.path.relpath(path, root)


def results_markdown(entries, root, extra_sections=()):
    """entries: [(block_name, run_dir)] with report.json (+ mutation.json)."""
    L = []
    L.append("# Feature 8 results: auto test generation + formal DV")
    L.append("")
    L.append("Generated by `python3 -m forge_testgen results` on %s from the JSON files named in "
             "each row. Every number is **measured** (a tool printed it into that file) unless "
             "marked **derived** (formula given)." % time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime()))
    L.append("")
    L.append("> **Scope.** The four blocks below are *fixtures written in this session* to exercise the "
             "tool. They are **not Forge Build 6 blocks**: the Build 6 RTL, formal tool #4 and "
             "conformance pack #5 were not present in this session's checkout. The Build 6 success "
             "test is therefore **not yet** run; see INTEGRATION.md for the exact steps.")
    L.append("")
    reports = []
    for name, d in entries:
        rp = os.path.join(d, "report.json")
        mp = os.path.join(d, "mutation.json")
        r = json.load(open(rp)) if os.path.exists(rp) else None
        m = json.load(open(mp)) if os.path.exists(mp) else None
        reports.append((name, d, r, m))
    if reports and reports[0][2]:
        tv = reports[0][2].get("tool_versions", {})
        L.append("Tools (measured, `tool_versions` in each report.json): " + "; ".join(
            "%s: %s" % (k, v.split(" (")[0]) for k, v in tv.items() if v))
        L.append("")
    L.append("## 1. Correct RTL: generated tests + proofs, no false positives")
    L.append("")
    L.append("| block | kind | tests (directed / random / closure) | coverage hit / reachable (excluded as proven unreachable) | simulation runs failing | formal verdict | formal time | source |")
    L.append("|---|---|---|---|---|---|---|---|")
    for name, d, r, m in reports:
        if not r:
            L.append("| %s | | not yet | | | | | |" % name)
            continue
        t = r.get("tests", {})
        cov = r.get("coverage", {})
        sims = r.get("simulation", {})
        fv = r.get("formal", {})
        L.append("| %s | %s | %s / %s / %s | %s / %s (%s) | %d of %d | %s | %ss | `%s` |" % (
            name, r["block"]["kind"], t.get("directed", 0), t.get("random", 0), t.get("closure", 0),
            cov.get("bins_hit"), cov.get("bins_considered"), cov.get("bins_excluded_unreachable"),
            sum(1 for v in sims.values() if not v["ok"]), len(sims), fv.get("verdict", "not run"),
            fv.get("seconds", ""), _rel(os.path.join(d, "report.json"), root)))
    L.append("")
    L.append("Coverage by bin kind (measured): " + "; ".join(
        "%s %s" % (name, r["coverage"].get("by_kind")) for name, d, r, m in reports if r))
    L.append("")
    for name, d, r, m in reports:
        fv = (r or {}).get("formal") or {}
        if fv.get("kind") == "stream_properties":
            L.append("- `%s` stream properties: %s; jobs: %s; covers reached: %s; unreached: %s." % (
                name, ", ".join(fv.get("labels", [])),
                ", ".join("%s=%s (%.0fs)" % (j["job"], j["status"], j["seconds"]) for j in fv.get("jobs", [])),
                ", ".join(fv.get("covers_reached", [])) or "none",
                ", ".join(fv.get("covers_unreached", [])) or "none"))
    L.append("")
    L.append("## 2. Injected bugs: what catches them")
    L.append("")
    L.append("Each mutant is the correct RTL with one source edit (operator, constant off-by-one, "
             "`$signed`->`$unsigned`, `>>>`->`>>`, negated/stuck `if`, dropped register update). "
             "A formal counterexample counts only if it replays in simulation. Mutants proven "
             "equivalent to the original (formal miter) are not bugs and are excluded; "
             "**derived** kill rate = killed / (valid - equivalent - spec-conformant).")
    L.append("")
    L.append("| block | mutants | stillborn | equivalent (proven / bounded) | spec-conformant | real bugs | killed by sim | killed by formal | killed (any) | survived | killed by directed tests alone | killed by random tests alone | source |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for name, d, r, m in reports:
        if not m:
            L.append("| %s | not yet | | | | | | | | | | | |" % name)
            continue
        s = m["summary"]
        L.append("| %s | %d | %d | %d / %d | %d | %d | %s | %s | %s | %d | %s | %s | `%s` |" % (
            name, s["mutants_total"], s["stillborn"], s["proven_equivalent"], s["bounded_equivalent"],
            s["spec_conformant_behavior_change"], s["denominator"], s["sim_kill_rate"],
            s["formal_kill_rate"], s["combined_kill_rate"], s["survived"],
            s["directed_only_kill_rate"], s["random_only_kill_rate"],
            _rel(os.path.join(d, "mutation.json"), root)))
    L.append("")
    L.append("Formal check per mutant (measured, `formal_mode` in mutation.json): " + "; ".join(
        "%s: %s" % (name, m.get("formal_mode", "?")) for name, d, r, m in reports if m) + ".")
    L.append("")
    for name, d, r, m in reports:
        if m and (m.get("survivors") or m.get("conformant")):
            L.append("- `%s` survivors: %s; spec-conformant: %s" % (
                name, m.get("survivors") or "none", m.get("conformant") or "none"))
    L.extend(extra_sections)
    return "\n".join(L) + "\n"
