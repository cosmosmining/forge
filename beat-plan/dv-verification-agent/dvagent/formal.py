def _replay(m, prep, stim, gate_rtl, workdir, sims, tv):
    rp = V.prepare_with_stimulus(m, stim, os.path.join(workdir, "replay_tb"), ports=prep.ports)
    opts = dict(seed=0, simulators=sims, coverage=False, lint=False, structural=False, jobs=1,
                trace_golden=False, tool_versions=tv or {})
    g = V.verify(m, V.Options(**opts), os.path.join(workdir, "replay_gold"), prep=rp)
    x = V.verify(m, V.Options(**opts, rtl_override=gate_rtl), os.path.join(workdir, "replay_gate"), prep=rp)
    return g, x


def _extra_seeds(m, prep, gate_rtl, workdir, sims, tv, seeds) -> dict:
    """Run the changed RTL against fresh random stimulus; the first failing seed is an escape."""
    from . import verify as V2
    for sd in seeds:
        p2 = V2.prepare(m, sd, os.path.join(workdir, f"seed{sd}_tb"), trace_golden=False)
        rep = V2.verify(m, V2.Options(seed=sd, simulators=sims, coverage=False, lint=False, structural=False,
                                      jobs=1, rtl_override=gate_rtl, trace_golden=False, tool_versions=tv or {}),
                        os.path.join(workdir, f"seed{sd}"), prep=p2)
        if rep["verdict"] == V.FAIL:
            learned = ([{k: v for k, v in b.items() if k != m.in_last} for b in p2.stim.beats]
                       if m.golden_style == "map" else _packets(m, p2.stim.beats))
            return {"failed_seed": sd, "reasons": rep.get("reasons", [])[:3], "learned": learned}
        shutil.rmtree(os.path.join(workdir, f"seed{sd}_tb"), ignore_errors=True)
    return {"failed_seed": None}


def _packets(m, beats):
    packets, cur = [], []
    for b in beats:
        cur.append({k: v for k, v in b.items() if k != m.in_last})
        if not m.in_last or b.get(m.in_last):
            packets.append(cur)
            cur = []
    return packets


def classify_survivor(m, prep, rec: dict, workdir: str, depth: int | None = None,
                      tv: dict | None = None, sims: list | None = None) -> dict:
    sims = sims or ["iverilog"]
    rtl_dir = os.path.join(rec["work"], "rtl")
    gold_rtl = m.rtl_paths
    order = {os.path.basename(f): i for i, f in enumerate(gold_rtl)}
    gate_rtl = sorted((os.path.join(rtl_dir, f) for f in os.listdir(rtl_dir)),
                      key=lambda f: order.get(os.path.basename(f), 99))
    fcfg = m.formal
    depth = depth or int(fcfg.get("depth", 20))
    bmc_t = int(fcfg.get("bmc_timeout_s", 120))
    if rec.get("op") == "EDGE":
        # yosys equiv and sby update every flop once per step whatever its clock edge,
        # and async resets become synchronous (async2sync): they cannot judge this change.
        return {"class": "needs-review", "method": "none",
                "note": "clock/reset edge change; cycle-based formal cannot judge it and the testbench "
                        "did not catch it - review by hand"}

    # 1. structural proof (all inputs, every cycle)
    ye = yosys_equiv(m, gold_rtl, gate_rtl, os.path.join(workdir, "equiv"))
    if ye["status"] == "proven":
        return {"class": "equivalent", "method": "yosys equiv_simple/equiv_induct", "script": ye.get("script")}
    out = {"yosys_equiv": ye["status"]}

    # 2. lockstep (cycle-level) check under the manifest's constraints and handshake rules
    cy = equivalence(m, prep.ports, gold_rtl, gate_rtl, os.path.join(workdir, "sby_cycle"),
                     depth=depth, mode="bmc", kind="cycle", timeout_s=bmc_t)
    out["cycle"] = {k: cy.get(k) for k in ("status", "mode", "depth", "detail", "sby")}
    if cy["status"] == "error":
        return {**out, "class": "unclassified", "method": "sby cycle bmc", "note": cy.get("detail")}
    if cy["status"] == "proven":  # comb: one step is complete
        return {**out, "class": "equivalent", "method": "sby bmc (combinational: complete)"}
    if cy["status"] == "bounded":
        pr = equivalence(m, prep.ports, gold_rtl, gate_rtl, os.path.join(workdir, "sby_pdr"), depth=depth,
                         mode="prove", kind="cycle", timeout_s=int(fcfg.get("prove_timeout_s", 60)),
                         engine=fcfg.get("prove_engine", "abc pdr"))
        out["prove"] = {k: pr.get(k) for k in ("status", "mode", "engine", "detail")}
        if pr["status"] == "proven":
            return {**out, "class": "equivalent", "method": f"sby {pr.get('engine')} (unbounded)"}
        return {**out, "class": "bounded-equivalent", "method": "sby bmc",
                "note": f"no difference within {depth} cycles from reset; unbounded proof did not close"}

    # 3. a cycle-level difference exists: is it functional?
    stim, learned = cycle_trace_to_stimulus(m, prep.ports, parse_vcd(cy["trace"]), cy["info"], prep.stim.gens)
    out["trace"] = cy["trace"]
    if stim is not None:
        g, x = _replay(m, prep, stim, gate_rtl, workdir, sims, tv)
        out.update(replay_gold=g["verdict"], replay_gate=x["verdict"])
        if g["verdict"] != V.PASS:
            return {**out, "class": "unclassified", "method": "sby cycle bmc + replay",
                    "note": "ORIGINAL RTL fails the replayed counterexample - check it and the manifest constraints",
                    "reasons": g.get("reasons", [])[:3]}
        if x["verdict"] == V.FAIL:
            return {**out, "class": "escape", "method": "sby cycle bmc + replay", "learned": learned,
                    "note": "functional difference the random tests missed; the replayed trace kills it",
                    "reasons": x.get("reasons", [])[:3]}
    if not cy["info"]["clocked"]:
        return {**out, "class": "unclassified", "method": "sby bmc + replay",
                "note": "formal difference not reproduced by the replay"}
    extra = [int(x) for x in fcfg.get("extra_seeds", [2, 3, 4, 5, 6, 7, 8, 9])]
    es = _extra_seeds(m, prep, gate_rtl, os.path.join(workdir, "extra_seeds"), sims, tv, extra)
    if es["failed_seed"] is not None:
        return {**out, "class": "escape", "method": "sby cycle bmc + extra random seeds", "learned": es["learned"],
                "note": f"missed by seed {prep.stim.seed}, caught by seed {es['failed_seed']}",
                "reasons": es["reasons"]}
    note = (f"cycle-level difference (formal trace); transactions equal on the replayed trace and on "
            f"{len(extra)} extra random seeds")
    if txn_applicable(m) and fcfg.get("txn_check", False):
        tx = equivalence(m, prep.ports, gold_rtl, gate_rtl, os.path.join(workdir, "sby_txn"),
                         depth=int(fcfg.get("txn_depth", 10)), mode="bmc", kind="txn",
                         timeout_s=int(fcfg.get("txn_timeout_s", 60)))
        out["txn"] = {k: tx.get(k) for k in ("status", "mode", "depth", "detail")}
        out["txn"]["beats"] = tx["info"]["beats"]
        if tx["status"] == "cex":
            return {**out, **_txn_escape(m, prep, tx, gate_rtl, workdir, sims, tv)}
        if tx["status"] == "bounded":
            note += (f"; transaction-level BMC found no difference for any legal timing with "
                     f"{tx['info']['beats']} beats in {tx.get('depth')} cycles")
        else:
            note += f"; transaction-level BMC inconclusive ({tx.get('detail')})"
    return {**out, "class": "timing-only", "method": "sby cycle bmc + replay + extra seeds", "note": note}


def _txn_escape(m, prep, tx, gate_rtl, workdir, sims, tv) -> dict:
    steps = parse_vcd(tx["trace"])
    an = txn_trace_analysis(m, prep.ports, steps, tx["info"], prep.stim.gens)
    beats = [dict(b) for b in an["beats"]]
    if m.golden_style == "stream" and m.in_last and beats and not beats[-1].get(m.in_last):
        beats[-1][m.in_last] = 1
    _, data_out = tbgen.split_ports(m, prep.ports)
    fn, gpath = golden.load_callable(m.golden_model, m.base_dir)
    exp, _ = golden.run(fn, gpath, m.golden_style, [dict(b) for b in beats], data_out, trace=False)
    lg, lm = an["logs"]["g"], an["logs"]["m"]
    k = next((i for i in range(min(len(lg), len(lm))) if lg[i] != lm[i]), None)
    res = {"method": "sby txn bmc", "trace": tx["trace"], "beats_used": beats, "differs_at_output": k,
           "gold_outputs": lg, "gate_outputs": lm, "golden_outputs": exp[:len(lg) + 1]}
    gold_ok = all(i < len(exp) and lg[i] == exp[i] for i in range(len(lg)))
    if not gold_ok:
        res.update(**{"class": "unclassified",
                      "note": "ORIGINAL RTL disagrees with the golden model on the formal trace - investigate"})
        return res
    stim, learned = _finish(m, [dict(b) for b in beats],
                            (an["gate_gaps"] + [0] * len(beats))[:len(beats)], an["gate_ready"], prep.stim.gens)
    res["learned"] = learned
    if k is None:
        res.update(**{"class": "escape", "note": "changed copy broke the output valid/ready protocol while stalled"})
    else:
        res.update(**{"class": "escape",
                      "note": f"output transaction {k} differs: golden {exp[k] if k < len(exp) else '?'}, "
                              f"original {lg[k]}, changed {lm[k]}"})
    if stim is not None:
        g, x = _replay(m, prep, stim, gate_rtl, workdir, sims, tv)
        res.update(replay_gold=g["verdict"], replay_gate=x["verdict"])
    return res
