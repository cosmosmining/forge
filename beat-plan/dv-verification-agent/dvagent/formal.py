def parse_vcd(path: str) -> list:
    """Per smt_step snapshot of every signal: [{'dv_formal_top.x': int|None, ...}]"""
    ids, scope, steps, cur = {}, [], {}, {}
    step_id = None
    with open(path) as f:
        for raw in f:
            line = raw.strip()
            if not line:
                continue
            if line.startswith("$scope"):
                scope.append(line.split()[2])
            elif line.startswith("$upscope"):
                scope.pop()
            elif line.startswith("$var"):
                parts = line.split()
                vid, name = parts[3], parts[4]
                ids[vid] = ".".join(scope + [name])
                if name == "smt_step":
                    step_id = vid
            elif line.startswith("#"):
                if "smt_step" in cur:
                    steps[cur["smt_step"]] = dict(cur)
            elif line[0] in "bB":
                val, vid = line[1:].split()
                if vid in ids:
                    v = None if any(c in val for c in "xXzZ") else int(val, 2)
                    cur["smt_step" if vid == step_id else ids[vid]] = v
            elif line[0] in "01xXzZ" and len(line) > 1:
                vid = line[1:]
                if vid in ids:
                    cur[ids[vid]] = None if line[0] in "xXzZ" else int(line[0])
    if "smt_step" in cur:
        steps[cur["smt_step"]] = dict(cur)
    return [steps[k] for k in sorted(k for k in steps if k is not None)]


def _beat_from_raw(data_in, gens, getraw) -> dict:
    b = {}
    for p in data_in:
        raw = getraw(p) or 0
        g = gens.get(p.name)
        signed = g.signed if g else p.signed
        b[p.name] = gm.to_signed(raw, p.width) if signed else raw
    return b


def _finish(m, beats, gaps, ready, gens):
    """Stimulus for the testbench plus the learned directed input (beats, or packets for stream models)."""
    if not beats:
        return None, []
    if m.golden_style == "stream" and m.in_last and not beats[-1].get(m.in_last):
        beats[-1][m.in_last] = 1  # close the open packet so its output appears
    stim = stimulus.Stimulus(beats=beats, gaps=gaps, ready=ready + [1] * 8,
                             sources={"formal_trace": len(beats)}, seed=0, gens=gens)
    if m.golden_style == "stream":
        packets, cur = [], []
        for b in beats:
            cur.append({k: v for k, v in b.items() if k != m.in_last})
            if not m.in_last or b.get(m.in_last):
                packets.append(cur)
                cur = []
        return stim, packets
    return stim, beats


def cycle_trace_to_stimulus(m, ports, steps: list, info: dict, gens: dict):
    """(Stimulus|None, learned) from a cycle-level counterexample."""
    data_in, _ = tbgen.split_ports(m, ports)
    top = "dv_formal_top"

    def val(st, name):
        v = st.get(f"{top}.{name}")
        return 0 if v is None else v

    if not info["clocked"]:
        b = _beat_from_raw(data_in, gens, lambda p: steps[-1].get(f"{top}.{p.name}"))
        return stimulus.Stimulus(beats=[b], gaps=[0], ready=[], sources={"formal_trace": 1}, seed=0,
                                 gens=gens), [b]
    R = info["reset_steps"]
    beats, gaps, ready = [], [], []
    last_hs, run_start = R - 1, None
    for k in range(R, len(steps)):
        st = steps[k]
        v = val(st, m.in_valid) if m.in_valid else 1
        rdy = (st.get(f"{top}.{m.in_ready}__g") or 0) if m.in_ready else 1
        if m.out_ready:
            ready.append(val(st, m.out_ready))
        if v and run_start is None:
            run_start = k
        if v and rdy:
            beats.append(_beat_from_raw(data_in, gens, lambda p, st=st: st.get(f"{top}.{p.name}")))
            gaps.append(max(0, run_start - (last_hs + 1)))
            last_hs, run_start = k, None
    return _finish(m, beats, gaps, ready, gens)


def txn_trace_analysis(m, ports, steps: list, info: dict, gens: dict) -> dict:
    """Beats, both copies' output logs, and the changed copy's handshake timing from a txn trace."""
    data_in, data_out = tbgen.split_ports(m, ports)
    top = "dv_formal_top"
    last = steps[-1]
    beats = []
    for i in range(info["beats"]):
        raw = last.get(f"{top}.dv_b{i}") or 0
        beats.append(_beat_from_raw(data_in, gens,
                                    lambda p, raw=raw: (raw >> info["beat_layout"][p.name][1]) & gm.mask(p.width)))

    def unpack(raw):
        out, off = {}, sum(w for _, w in info["out_layout"])
        for name, w in info["out_layout"]:
            off -= w
            v = ((raw or 0) >> off) & gm.mask(w)
            p = next(x for x in data_out if x.name == name)
            out[name] = gm.to_signed(v, w) if p.signed else v
        return out

    logs = {}
    for c in ("g", "m"):
        n = last.get(f"{top}.dv_oc_{c}") or 0
        logs[c] = [unpack(last.get(f"{top}.dv_log_{c}{k}")) for k in range(min(n, info["beats"]))]
    R = info["reset_steps"]
    gaps, ready, consumed = [], [], 0
    last_hs, run_start = R - 1, None
    for k in range(R, len(steps)):
        st = steps[k]
        v = st.get(f"{top}.dv_inv_m") or 0
        rdy = (st.get(f"{top}.o_{m.in_ready}__m") or 0) if m.in_ready else 1
        if m.out_ready:
            ready.append(st.get(f"{top}.dv_ordy_m") or 0)
        if v and run_start is None:
            run_start = k
        if v and rdy:
            gaps.append(max(0, run_start - (last_hs + 1)))
            last_hs, run_start = k, None
            consumed += 1
    return {"beats": beats, "logs": logs, "gate_gaps": gaps, "gate_ready": ready, "gate_consumed": consumed}


