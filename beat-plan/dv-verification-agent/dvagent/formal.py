"""Formal checks with yosys and SymbiYosys: is a changed design distinguishable from the original?

Checks, cheapest first (classify_survivor):

1. yosys equiv_make / equiv_simple / equiv_induct - structural equivalence over all
   inputs at every cycle. A proof here is sound; "unproven" just means ask sby.
2. cycle-level (lockstep) check: the same free inputs drive both copies, under the
   manifest's input constraints and the testbench's handshake rules; outputs are
   compared where the testbench compares them. Comb: one step is a complete proof.
   Clocked: BMC (bitwuzla), and when clean an unbounded proof attempt (ABC PDR).
3. when the lockstep check finds a difference: replay the trace through the normal
   testbench, then fresh random seeds; any failure there is an escape. Optionally
   (formal.txn_check) a transaction-level BMC: N symbolic beats shared by both copies,
   each copy with its own free valid/ready/junk timing, k-th output transactions must
   match. It is sound but slow with the open-source solvers, so it is off by default.

Classes: equivalent (proven), bounded-equivalent (no difference within the bounds),
timing-only (cycle-level difference; transactions equal on the replay and extra seeds),
needs-review (clock/reset edge changes, which cycle-based formal cannot judge),
escape (functional difference the tests missed), unclassified (tool problem).
Escapes come with learned input beats from the counterexample.
"""

from __future__ import annotations

import os
import re
import shutil

from . import gm, golden, stimulus, tbgen, tools
from . import verify as V
from .introspect import _chparams


def _lit(v: int, w: int) -> str:
    return f"{w}'sd{v}" if v >= 0 else f"-{w}'sd{-v}"


def _domain_checks(m, ports, getter) -> list:
    """Boolean SV expressions constraining input values. getter(port, hi_bit, lo_bit) -> SV expr."""
    out = []
    data_in, _ = tbgen.split_ports(m, ports)
    for p in data_in:
        cfg = m.port_cfg.get(p.name, {})
        signed = bool(cfg.get("signed", p.signed))
        full = getter(p, p.width - 1, 0)
        if cfg.get("values"):
            vals = [int(v) & gm.mask(p.width) for v in cfg["values"]]
            out.append("(" + " || ".join(f"({full} == {p.width}'h{v:x})" for v in vals) + ")")
            continue
        segs = []
        if "range" in cfg:
            segs.append((p.width - 1, 0, signed, int(cfg["range"][0]), int(cfg["range"][1])))
        n = int(cfg.get("lanes", 1))
        if n > 1 and "lane_range" in cfg:
            lw = p.width // n
            ls = bool(cfg.get("lane_signed", True))
            for i in range(n):
                segs.append((lw * i + lw - 1, lw * i, ls, int(cfg["lane_range"][0]), int(cfg["lane_range"][1])))
        for hi_b, lo_b, sg, lo, hi in segs:
            e = getter(p, hi_b, lo_b)
            w = hi_b - lo_b + 1
            top = getter(p, hi_b, hi_b)
            ext = f"$signed({{{{2{{{top}}}}}, {e}}})" if sg else f"$signed({{2'b00, {e}}})"
            out.append(f"(({ext} >= {_lit(lo, w + 2)}) && ({ext} <= {_lit(hi, w + 2)}))")
    return out


def _reset_lines(m, R) -> list:
    L = ["  reg [7:0] dv_cyc = 8'd0;",
         f"  always @(posedge {m.clock}) if (dv_cyc != 8'hff) dv_cyc <= dv_cyc + 8'd1;",
         f"  wire dv_in_rst = (dv_cyc < 8'd{R});"]
    if m.reset:
        on, off = ("1'b0", "1'b1") if m.reset_active_low else ("1'b1", "1'b0")
        L.append(f"  wire dv_rst = dv_in_rst ? {on} : {off};")
    return L


# ---- cycle-level wrapper -----------------------------------------------------

def write_cycle_wrapper(m, ports, path: str) -> dict:
    data_in, data_out = tbgen.split_ports(m, ports)
    clocked = m.protocol != "comb"
    latency = m.latency if (clocked and not m.out_valid) else 0
    L = ["// Generated by the Forge DV agent: gold vs gate, cycle-level comparison.",
         "module dv_formal_top ("]
    decl = [f"  input logic {m.clock}"] if clocked else []
    for p in ports:
        if p.direction == "input" and p.name not in (m.clock, m.reset):
            decl.append(f"  input logic [{p.width - 1}:0] {p.name}")
    L += [",\n".join(decl), ");"]
    for p in ports:
        if p.direction == "output":
            L.append(f"  wire [{p.width - 1}:0] {p.name}__g, {p.name}__m;")
    R = max(1, m.reset_cycles)
    if clocked:
        L += _reset_lines(m, R)

    def conns(sfx):
        c = []
        for p in ports:
            if p.direction == "output":
                c.append(f".{p.name}({p.name}__{sfx})")
            elif p.name == m.reset:
                c.append(f".{p.name}(dv_rst)")
            else:
                c.append(f".{p.name}({p.name})")
        return ", ".join(c)

    L.append(f"  dv_gold u_g ({conns('g')});")
    L.append(f"  dv_gate u_m ({conns('m')});")
    cons = _domain_checks(m, ports, lambda p, h, l: p.name if (h, l) == (p.width - 1, 0) else f"{p.name}[{h}:{l}]")
    eq_data = " && ".join(f"({p.name}__g == {p.name}__m)" for p in data_out)
    if not clocked:
        L.append("  always @* begin")
        L += [f"    assume ({c});" for c in cons]
        L.append(f"    assert ({eq_data});")
        L.append("  end")
    else:
        valid_in = m.in_valid or "1'b1"
        if cons:
            L.append("  always @* begin")
            L += [f"    if ({valid_in}) assume ({c});" for c in cons]
            L.append("  end")
        if m.in_valid:
            L.append(f"  always @* if (dv_in_rst) assume (!{m.in_valid});")
        if m.in_ready and m.in_valid:
            cat = "{" + ", ".join(p.name for p in data_in) + "}"
            w = sum(p.width for p in data_in)
            L += ["  reg dv_stall = 1'b0;", f"  reg [{w - 1}:0] dv_hold = '0;",
                  f"  always @(posedge {m.clock}) begin",
                  f"    dv_stall <= !dv_in_rst && {m.in_valid} && !{m.in_ready}__g;",
                  f"    dv_hold <= {cat};", "  end",
                  f"  always @* if (dv_stall) assume ({m.in_valid} && ({cat} == dv_hold));"]
        if not m.out_valid:
            L.append(f"  wire dv_cap = !dv_in_rst && {valid_in};")
            if latency >= 1:
                L.append(f"  reg [{latency - 1}:0] dv_hist = '0;")
                shift = "dv_cap" if latency == 1 else f"{{dv_hist[{latency - 2}:0], dv_cap}}"
                L.append(f"  always @(posedge {m.clock}) dv_hist <= {shift};")
                L.append(f"  wire dv_cmp = dv_hist[{latency - 1}];")
            else:
                L.append("  wire dv_cmp = dv_cap;")
        L += ["  always @* begin", "    if (!dv_in_rst) begin"]
        if m.out_valid:
            L.append(f"      assert ({m.out_valid}__g == {m.out_valid}__m);")
            L.append(f"      if ({m.out_valid}__g) assert ({eq_data});")
        else:
            L.append(f"      if (dv_cmp) assert ({eq_data});")
        if m.in_ready:
            L.append(f"      assert ({m.in_ready}__g == {m.in_ready}__m);")
        L += ["    end", "  end"]
    L.append("endmodule")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    return {"kind": "cycle", "clocked": clocked, "latency": latency, "reset_steps": R if clocked else 0,
            "constraints": cons}


# ---- transaction-level wrapper ---------------------------------------------------

def txn_applicable(m) -> bool:
    return m.protocol != "comb" and bool(m.in_valid) and bool(m.out_valid)


def write_txn_wrapper(m, ports, path: str, n_beats: int) -> dict:
    data_in, data_out = tbgen.split_ports(m, ports)
    N = max(1, n_beats)
    PW = max(1, (N + 1).bit_length())
    CW = PW
    BW = sum(p.width for p in data_in)
    OW = sum(p.width for p in data_out)
    R = max(1, m.reset_cycles)
    hold = {p.name for p in data_in
            if m.port_cfg.get(p.name, {}).get("hold") or not m.stimulus.get("junk_when_idle", True)}
    pos, off = {}, BW   # bit range of each data input inside a beat vector (first port in the MSBs)
    for p in data_in:
        off -= p.width
        pos[p.name] = (off + p.width - 1, off)
    L = ["// Generated by the Forge DV agent: gold vs gate, transaction-level comparison.",
         "module dv_formal_top ("]
    decl = [f"  input logic {m.clock}", "  input logic dv_iv_g", "  input logic dv_iv_m"]
    if m.out_ready:
        decl += ["  input logic dv_or_g", "  input logic dv_or_m"]
    decl += [f"  input logic [{BW - 1}:0] dv_junk_g", f"  input logic [{BW - 1}:0] dv_junk_m"]
    L += [",\n".join(decl), ");"]
    L += _reset_lines(m, R)
    for i in range(N):
        L.append(f"  (* anyconst *) reg [{BW - 1}:0] dv_b{i};")
    cons_all = []
    for i in range(N):
        cons_all += _domain_checks(m, ports, lambda p, h, l, i=i: f"dv_b{i}[{pos[p.name][1] + h}:{pos[p.name][1] + l}]")
    if cons_all:
        L.append("  always @* begin")
        L += [f"    assume ({c});" for c in cons_all]
        L.append("  end")
    for c in ("g", "m"):
        L.append(f"  // ---- copy {c}: environment, DUT, output log")
        L.append(f"  reg [{PW - 1}:0] dv_ip_{c} = '0;")
        L.append(f"  reg dv_vh_{c} = 1'b0;")
        L.append(f"  wire dv_have_{c} = (dv_ip_{c} < {PW}'d{N});")
        L.append(f"  wire dv_inv_{c} = !dv_in_rst && dv_have_{c} && (dv_vh_{c} || dv_iv_{c});")
        mux = f"dv_b{N - 1}"
        for i in reversed(range(N - 1)):
            mux = f"(dv_ip_{c} == {PW}'d{i}) ? dv_b{i} : {mux}"
        L.append(f"  wire [{BW - 1}:0] dv_cur_{c} = {mux};")
        for p in data_in:
            h, l = pos[p.name]
            src = f"dv_cur_{c}[{h}:{l}]"
            if p.name not in hold:
                src = f"(dv_inv_{c} ? dv_cur_{c}[{h}:{l}] : dv_junk_{c}[{h}:{l}])"
            L.append(f"  wire [{p.width - 1}:0] {p.name}__{c} = {src};")
        for p in ports:
            if p.direction == "output":
                L.append(f"  wire [{p.width - 1}:0] o_{p.name}__{c};")
        rdy_in = f"o_{m.in_ready}__{c}" if m.in_ready else "1'b1"
        L.append(f"  wire dv_ihs_{c} = dv_inv_{c} && {rdy_in};")
        orr = f"(!dv_in_rst && dv_or_{c})" if m.out_ready else "1'b1"
        L.append(f"  wire dv_ordy_{c} = {orr};")
        L.append(f"  wire dv_ohs_{c} = !dv_in_rst && o_{m.out_valid}__{c} && dv_ordy_{c};")
        L.append(f"  always @(posedge {m.clock}) begin")
        L.append(f"    if (dv_ihs_{c}) dv_ip_{c} <= dv_ip_{c} + {PW}'d1;")
        L.append(f"    dv_vh_{c} <= dv_inv_{c} && !{rdy_in};")
        L.append("  end")
        conn = []
        for p in ports:
            if p.direction == "output":
                conn.append(f".{p.name}(o_{p.name}__{c})")
            elif p.name == m.clock:
                conn.append(f".{p.name}({m.clock})")
            elif p.name == m.reset:
                conn.append(f".{p.name}(dv_rst)")
            elif p.name == m.in_valid:
                conn.append(f".{p.name}(dv_inv_{c})")
            elif p.name == m.out_ready:
                conn.append(f".{p.name}(dv_ordy_{c})")
            else:
                conn.append(f".{p.name}({p.name}__{c})")
        L.append(f"  dv_{'gold' if c == 'g' else 'gate'} u_{c} ({', '.join(conn)});")
        ocat = "{" + ", ".join(f"o_{p.name}__{c}" for p in data_out) + "}"
        L.append(f"  wire [{OW - 1}:0] dv_odata_{c} = {ocat};")
        L.append(f"  reg [{CW - 1}:0] dv_oc_{c} = '0;")
        for k in range(N):
            L.append(f"  reg [{OW - 1}:0] dv_log_{c}{k} = '0;")
        L.append(f"  always @(posedge {m.clock}) if (dv_ohs_{c} && dv_oc_{c} < {CW}'d{N}) begin")
        for k in range(N):
            L.append(f"    if (dv_oc_{c} == {CW}'d{k}) dv_log_{c}{k} <= dv_odata_{c};")
        L.append(f"    dv_oc_{c} <= dv_oc_{c} + {CW}'d1;")
        L.append("  end")
    L.append("  // ---- the k-th output transaction of both copies must match")
    L.append("  always @* begin")
    for k in range(N):
        L.append(f"    if (dv_oc_g > {CW}'d{k} && dv_oc_m > {CW}'d{k}) assert (dv_log_g{k} == dv_log_m{k});")
    L.append("  end")
    if m.out_ready and m.checks.get("output_protocol", True):
        L += ["  // ---- the changed copy must hold out_valid and data while stalled",
              "  reg dv_ost_m = 1'b0;", f"  reg [{OW - 1}:0] dv_oh_m = '0;",
              f"  always @(posedge {m.clock}) begin",
              f"    dv_ost_m <= !dv_in_rst && o_{m.out_valid}__m && !dv_ordy_m;",
              "    dv_oh_m <= dv_odata_m;", "  end",
              f"  always @* if (dv_ost_m) assert (o_{m.out_valid}__m && (dv_odata_m == dv_oh_m));"]
    L.append("endmodule")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    return {"kind": "txn", "clocked": True, "reset_steps": R, "beats": N, "beat_layout": pos,
            "out_layout": [(p.name, p.width) for p in data_out], "constraints": cons_all}


# ---- running yosys / sby -------------------------------------------------------

def _read_flags(m) -> str:
    flags = ["-sv"] + [f"-I{d}" for d in m.include_paths]
    for k, v in (m.defines or {}).items():
        flags.append(f"-D{k}={v}" if v not in (None, "", True) else f"-D{k}")
    return " ".join(flags)


def yosys_equiv(m, gold_rtl: list, gate_rtl: list, workdir: str, seq: int = 5, timeout_s: int = 120) -> dict:
    """Structural equivalence, all inputs, every cycle. Sound when it proves."""
    if tools.which("yosys") is None:
        return {"status": "error", "detail": "yosys not installed"}
    os.makedirs(workdir, exist_ok=True)
    chp = _chparams(m.parameters)
    lines = []
    for tag, files in (("gold", gold_rtl), ("gate", gate_rtl)):
        lines += [f"read_verilog {_read_flags(m)} " + " ".join(f'"{os.path.abspath(f)}"' for f in files),
                  f"hierarchy -top {m.top} {chp}".strip(), "proc", "flatten", "opt_clean",
                  f"hierarchy -top {m.top}", f"rename {m.top} {tag}", f"design -stash {tag}"]
    lines += ["design -copy-from gold -as gold gold", "design -copy-from gate -as gate gate",
              "async2sync", "equiv_make gold gate equiv", "hierarchy -top equiv",
              f"equiv_simple -seq {seq}", f"equiv_induct -seq {seq}", "equiv_status -assert"]
    ys = os.path.join(workdir, "equiv.ys")
    with open(ys, "w") as f:
        f.write("\n".join(lines) + "\n")
    r = tools.run(["yosys", "-q", ys], cwd=workdir, timeout=timeout_s)
    if r.timed_out:
        return {"status": "error", "detail": f"yosys equiv timed out after {timeout_s}s", "script": ys}
    if r.rc == 0:
        return {"status": "proven", "script": ys}
    m2 = re.search(r"Found (\d+) unproven \$equiv cells", r.out)
    if m2:
        return {"status": "unproven", "unproven_cells": int(m2.group(1)), "script": ys}
    return {"status": "error", "detail": r.out.strip()[-600:], "script": ys}


def run_sby(m, gold_rtl, gate_rtl, workdir, wrapper_info, mode, depth, engine=None, timeout_s=120) -> dict:
    if tools.which("sby") is None:
        return {"status": "error", "detail": "sby not installed"}
    engine = engine or m.formal.get("engine", "smtbmc bitwuzla")
    chp = _chparams(m.parameters)
    script = []
    for tag, files in (("gold", gold_rtl), ("gate", gate_rtl)):
        script += [f"read_verilog {_read_flags(m)} " + " ".join(f"{tag}/{os.path.basename(f)}" for f in files),
                   f"hierarchy -top {m.top} {chp}".strip(), "proc", "flatten", f"hierarchy -top {m.top}",
                   f"rename {m.top} dv_{tag}", f"design -stash {tag}"]
    script += ["design -copy-from gold -as dv_gold dv_gold", "design -copy-from gate -as dv_gate dv_gate",
               "read_verilog -sv -formal dv_formal_top.sv", "prep -top dv_formal_top"]
    files = [f"gold/{os.path.basename(f)} {os.path.abspath(f)}" for f in gold_rtl]
    files += [f"gate/{os.path.basename(f)} {os.path.abspath(f)}" for f in gate_rtl]
    files.append(f"dv_formal_top.sv {os.path.join(workdir, 'dv_formal_top.sv')}")
    sby = "\n".join(["[options]", f"mode {mode}", f"depth {depth}", "multiclock off", "",
                     "[engines]", engine, "", "[script]"] + script + ["", "[files]"] + files) + "\n"
    sby_path = os.path.join(workdir, "eq.sby")
    with open(sby_path, "w") as f:
        f.write(sby)
    shutil.rmtree(os.path.join(workdir, "eq"), ignore_errors=True)
    r = tools.run(["sby", "-f", "eq.sby"], cwd=workdir, timeout=timeout_s)
    out = r.out or ""
    trace = os.path.join(workdir, "eq", "engine_0", "trace.vcd")
    res = {"mode": mode, "depth": depth, "engine": engine, "sby": sby_path, "log_tail": out[-2000:]}
    if r.timed_out:
        res.update(status="error", detail=f"sby timed out after {timeout_s}s")
    elif "DONE (PASS" in out:
        res["status"] = "proven" if (mode == "prove" or not wrapper_info["clocked"]) else "bounded"
    elif "DONE (FAIL" in out and os.path.isfile(trace):
        res.update(status="cex", trace=trace)
    elif "DONE (UNKNOWN" in out or (mode == "prove" and "DONE (FAIL" in out):
        res["status"] = "bounded"   # basecase clean, induction did not close
    else:
        res.update(status="error", detail="sby did not finish cleanly")
    return res


def equivalence(m, ports, gold_rtl: list, gate_rtl: list, workdir: str, depth: int | None = None,
                mode: str = "bmc", kind: str = "cycle", timeout_s: int | None = None,
                engine: str | None = None) -> dict:
    """Constrained gold-vs-gate check. kind: cycle | txn. Returns run_sby() result + wrapper info."""
    shutil.rmtree(workdir, ignore_errors=True)
    os.makedirs(workdir)
    wpath = os.path.join(workdir, "dv_formal_top.sv")
    if kind == "txn":
        info = write_txn_wrapper(m, ports, wpath, int(m.formal.get("txn_beats", 6)))
    else:
        info = write_cycle_wrapper(m, ports, wpath)
    depth = depth or int(m.formal.get("depth", 20))
    if not info["clocked"]:
        mode, depth = "bmc", 1
    res = run_sby(m, gold_rtl, gate_rtl, workdir, info, mode, depth, engine=engine,
                  timeout_s=timeout_s or int(m.formal.get("bmc_timeout_s", 120)))
    res["info"] = info
    res["kind"] = kind
    return res


