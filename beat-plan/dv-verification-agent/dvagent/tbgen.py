"""Testbench writer.

Writes a self-checking SystemVerilog testbench (plain Verilog-2001 constructs
plus `timescale and $value$plusargs, so it runs on Icarus and Verilator) and
the $readmemh files it reads:

  in_<port>.hex   input beats            exp_<port>.hex  golden output beats
  gap.hex         idle cycles per beat   rdy.hex         out_ready per cycle

Timing discipline: inputs change 1 time unit after posedge (like clock-to-q of
the upstream flops) and the DUT is sampled at posedge (pre-NBA values). This is
race-free for DUTs that use non-blocking assignments, and unlike negedge
driving it does not hide flops that wrongly use the falling edge.

The testbench compares every output beat with `!==` (so X fails), counts
missing / extra outputs and X on control outputs, stops on a cycle timeout,
dumps every observed output beat for an independent Python compare, and prints
one DVAGENT_RESULT line.
"""

from __future__ import annotations

import json
import os

from . import gm


def _rng(width: int) -> str:
    return f"[{width - 1}:0]"


def _hex(v: int, width: int) -> str:
    return format(v & gm.mask(width), "0{}x".format((width + 3) // 4))


def _write_mem(path: str, values: list, width: int) -> None:
    if not values:
        values = [0]
    with open(path, "w") as f:
        for v in values:
            f.write(_hex(int(v), width) + "\n")


def _param_override(params: dict) -> str:
    if not params:
        return ""
    items = []
    for k, v in params.items():
        if isinstance(v, bool):
            v = int(v)
        items.append(f".{k}({v})" if isinstance(v, int) else f'.{k}("{v}")')
    return " #(" + ", ".join(items) + ")"


def split_ports(manifest, ports):
    data_in = [p for p in ports if p.direction == "input" and p.name not in manifest.control_inputs]
    data_out = [p for p in ports if p.direction == "output" and p.name not in manifest.control_outputs]
    return data_in, data_out


def auto_timeout(n_in: int, gaps: list, ready: list, latency: int) -> int:
    stalls = sum(1 for r in ready if r == 0)
    return 2000 + 20 * (n_in + sum(gaps)) + stalls + 50 * (latency + 1)


def write(manifest, ports, stim, expected, out_dir: str) -> dict:
    """Write tb.sv and its data files into out_dir. Returns metadata."""
    os.makedirs(out_dir, exist_ok=True)
    m = manifest
    data_in, data_out = split_ports(m, ports)
    if not data_out:
        raise ValueError(f"{m.top} has no data outputs to check")
    n_in, n_out = len(stim.beats), len(expected)
    clocked = m.protocol != "comb"
    latency = m.latency if (clocked and not m.out_valid) else 0

    for p in data_in:
        _write_mem(os.path.join(out_dir, f"in_{p.name}.hex"), [b[p.name] for b in stim.beats], p.width)
    for p in data_out:
        _write_mem(os.path.join(out_dir, f"exp_{p.name}.hex"), [e[p.name] for e in expected], p.width)
    if clocked:
        _write_mem(os.path.join(out_dir, "gap.hex"), [min(g, 255) for g in stim.gaps], 8)
        _write_mem(os.path.join(out_dir, "rdy.hex"), stim.ready, 1)

    timeout = m.timeout_cycles or auto_timeout(n_in, stim.gaps, stim.ready, latency)
    check_out_proto = bool(clocked and m.out_valid and m.out_ready and m.checks.get("output_protocol", True))
    drain = 50 + 4 * latency

    L = []
    a = L.append
    a("`timescale 1ns/1ps")
    a(f"// Generated by the Forge DV agent for block {m.name} (top {m.top}).")
    a("// Regenerate with `dv tbgen`; do not hand-edit.")
    a("module dvagent_tb;")
    a(f"  localparam integer N_IN = {n_in};")
    a(f"  localparam integer N_OUT = {n_out};")
    if clocked:
        a(f"  localparam integer N_RDY = {len(stim.ready)};")
        a(f"  localparam integer TIMEOUT = {timeout};")
        a(f"  localparam integer DRAIN = {drain};")
    a("")
    for p in ports:
        kind = "reg " if p.direction == "input" else "wire"
        a(f"  {kind} {_rng(p.width)} {p.name};")
    a("")
    for p in data_in:
        a(f"  reg {_rng(p.width)} dv_in_{p.name} [0:{max(n_in, 1) - 1}];")
    for p in data_out:
        a(f"  reg {_rng(p.width)} dv_exp_{p.name} [0:{max(n_out, 1) - 1}];")
    if clocked:
        a(f"  reg [7:0] dv_gaps [0:{max(n_in, 1) - 1}];")
        a(f"  reg [0:0] dv_rdy [0:{max(len(stim.ready), 1) - 1}];")
    a("  reg [8*256-1:0] dv_fname;")
    a("  integer dv_fd, dv_err, dv_extra, dv_xctl, dv_in_idx, dv_out_idx;")
    a("")
    conns = ",\n".join(f"    .{p.name}({p.name})" for p in ports)
    a(f"  {m.top}{_param_override(m.parameters)} dut (\n{conns}\n  );")
    a("")

    fmt = " ".join(["%0d"] + ["%h"] * len(data_out))
    vals = ", ".join(["dv_out_idx"] + [p.name for p in data_out])
    cmp = " || ".join(f"({p.name} !== dv_exp_{p.name}[dv_out_idx])" for p in data_out)
    record = [
        f'      $fwrite(dv_fd, "{fmt}\\n", {vals});',
        "      if (dv_out_idx < N_OUT) begin",
        f"        if ({cmp}) begin",
        "          dv_err = dv_err + 1;",
        '          if (dv_err <= 5) $display("DVAGENT_MISMATCH idx=%0d", dv_out_idx);',
        "        end",
        "      end else begin",
        "        dv_extra = dv_extra + 1;",
        "      end",
        "      dv_out_idx = dv_out_idx + 1;",
    ]

    loads = []
    for p in data_in:
        loads.append(f'    $readmemh("in_{p.name}.hex", dv_in_{p.name});')
    for p in data_out:
        loads.append(f'    $readmemh("exp_{p.name}.hex", dv_exp_{p.name});')
    if clocked:
        loads.append('    $readmemh("gap.hex", dv_gaps);')
        loads.append('    $readmemh("rdy.hex", dv_rdy);')

    if not clocked:
        a("  initial begin : dv_main")
        a('    if (!$value$plusargs("dvout=%s", dv_fname)) dv_fname = "dv_out.txt";')
        L.extend(loads)
        a("    dv_fd = $fopen(dv_fname, \"w\");")
        a("    dv_err = 0; dv_extra = 0; dv_xctl = 0; dv_in_idx = 0; dv_out_idx = 0;")
        a("    for (dv_in_idx = 0; dv_in_idx < N_IN; dv_in_idx = dv_in_idx + 1) begin")
        for p in data_in:
            a(f"      {p.name} = dv_in_{p.name}[dv_in_idx];")
        a("      #5;")
        L.extend(["  " + r for r in record])
        a("      #5;")
        a("    end")
        a("    $fclose(dv_fd);")
        a('    $display("DVAGENT_RESULT outputs=%0d expected=%0d mismatches=%0d extra=%0d missing=%0d '
          'timeout=0 xctl=%0d consumed=%0d", dv_out_idx, N_OUT, dv_err, dv_extra, '
          '(dv_out_idx < N_OUT) ? (N_OUT - dv_out_idx) : 0, dv_xctl, dv_in_idx);')
        a("    $finish;")
        a("  end")
        a("endmodule")
    else:
        rst_on = "1'b0" if m.reset_active_low else "1'b1"
        rst_off = "1'b1" if m.reset_active_low else "1'b0"
        junk_w = max([32] + [p.width for p in data_in])
        n_words = (junk_w + 31) // 32
        a(f"  reg [{32 * n_words - 1}:0] dv_junk;")
        a("  reg dv_rst_done, dv_cap;")
        a("  integer dv_cyc, dv_gap, dv_seen, dv_rdy_idx, dv_proto;")
        if check_out_proto:
            dw = sum(p.width for p in data_out)
            a("  reg dv_ostall;")
            a(f"  reg [{dw - 1}:0] dv_ohold;")
        if latency >= 1:
            a(f"  reg [{latency - 1}:0] dv_hist;")
        a("")
        a(f"  initial {m.clock} = 1'b0;")
        a(f"  always #5 {m.clock} = ~{m.clock};")
        a("")
        a("  initial begin : dv_main")
        a('    if (!$value$plusargs("dvout=%s", dv_fname)) dv_fname = "dv_out.txt";')
        L.extend(loads)
        a("    dv_fd = $fopen(dv_fname, \"w\");")
        a("    dv_err = 0; dv_extra = 0; dv_xctl = 0; dv_in_idx = 0; dv_out_idx = 0; dv_cyc = 0;")
        a("    dv_rst_done = 1'b0; dv_cap = 1'b0; dv_proto = 0;")
        if check_out_proto:
            a("    dv_ostall = 1'b0; dv_ohold = '0;")
        if latency >= 1:
            a("    dv_hist = '0;")
        if m.reset:
            a(f"    {m.reset} = {rst_on};")
        if m.in_valid:
            a(f"    {m.in_valid} = 1'b0;")
        if m.out_ready:
            a(f"    {m.out_ready} = 1'b0;")
        for p in data_in:
            a(f"    {p.name} = '0;")
        a(f"    repeat ({max(1, m.reset_cycles)}) @(posedge {m.clock});")
        a("    #1;")
        if m.reset:
            a(f"    {m.reset} = {rst_off};")
        a("    dv_rst_done = 1'b1;")
        a(f"    while ((dv_out_idx < N_OUT) && (dv_cyc < TIMEOUT)) @(posedge {m.clock});")
        a(f"    repeat (DRAIN) @(posedge {m.clock});")
        a("    $fclose(dv_fd);")
        a('    $display("DVAGENT_RESULT outputs=%0d expected=%0d mismatches=%0d extra=%0d missing=%0d '
          'timeout=%0d xctl=%0d consumed=%0d proto=%0d", dv_out_idx, N_OUT, dv_err, dv_extra, '
          '(dv_out_idx < N_OUT) ? (N_OUT - dv_out_idx) : 0, (dv_cyc >= TIMEOUT) ? 1 : 0, dv_xctl, dv_in_idx, '
          'dv_proto);')
        a("    $finish;")
        a("  end")
        a("")
        # driver: changes inputs 1 time unit after posedge
        junk_expr = "{" + ", ".join(["$random"] * n_words) + "}"
        a("  initial begin : dv_drv")
        a("    dv_seen = -1; dv_gap = 0;")
        a("    wait (dv_rst_done == 1'b1);")
        a("    forever begin")
        a("      if (dv_in_idx < N_IN) begin")
        a("        if (dv_in_idx != dv_seen) begin dv_seen = dv_in_idx; dv_gap = dv_gaps[dv_in_idx]; end")
        a("        if (dv_gap > 0) begin")
        if m.in_valid:
            a(f"          {m.in_valid} = 1'b0;")
        for p in data_in:  # fresh random junk per port while idle
            if not getattr(_gen_lookup(stim, p.name), "hold", False):
                a(f"          dv_junk = {junk_expr}; {p.name} = dv_junk[{p.width - 1}:0];")
        a("          dv_gap = dv_gap - 1;")
        a("        end else begin")
        if m.in_valid:
            a(f"          {m.in_valid} = 1'b1;")
        for p in data_in:
            a(f"          {p.name} = dv_in_{p.name}[dv_in_idx];")
        a("        end")
        a("      end else begin")
        if m.in_valid:
            a(f"        {m.in_valid} = 1'b0;")
        for p in data_in:
            if not getattr(_gen_lookup(stim, p.name), "hold", False):
                a(f"        dv_junk = {junk_expr}; {p.name} = dv_junk[{p.width - 1}:0];")
        a("      end")
        a(f"      @(posedge {m.clock}); #1;")
        a("    end")
        a("  end")
        a("")
        if m.out_ready:
            a("  initial begin : dv_rdy_drv")
            a("    dv_rdy_idx = 0;")
            a("    wait (dv_rst_done == 1'b1);")
            a("    forever begin")
            a(f"      {m.out_ready} = (dv_rdy_idx < N_RDY) ? dv_rdy[dv_rdy_idx] : 1'b1;")
            a("      dv_rdy_idx = dv_rdy_idx + 1;")
            a(f"      @(posedge {m.clock}); #1;")
            a("    end")
            a("  end")
            a("")
        # monitor: all handshake bookkeeping in one process, sampled at posedge
        in_rdy = f"({m.in_ready} === 1'b1)" if m.in_ready else "1'b1"
        if m.in_valid:
            cap = f"({m.in_valid} === 1'b1) && {in_rdy} && (dv_in_idx < N_IN)"
        else:
            cap = "(dv_in_idx < N_IN)"
        a(f"  always @(posedge {m.clock}) begin : dv_mon")
        a("    if (dv_rst_done) begin")
        a("      dv_cyc = dv_cyc + 1;")
        a(f"      dv_cap = {cap};")
        if m.out_valid:
            a(f"      if ((^{m.out_valid}) === 1'bx) dv_xctl = dv_xctl + 1;")
        if m.in_ready:
            guard = f"({m.in_valid} === 1'b1) && " if m.in_valid else ""
            a(f"      if ({guard}((^{m.in_ready}) === 1'bx)) dv_xctl = dv_xctl + 1;")
        if check_out_proto:
            cat = "{" + ", ".join(p.name for p in data_out) + "}"
            a("      // output protocol: once out_valid is up it stays up, with the same data, until out_ready")
            a(f"      if (dv_ostall && (({m.out_valid} !== 1'b1) || ({cat} !== dv_ohold))) begin")
            a("        dv_proto = dv_proto + 1;")
            a('        if (dv_proto <= 5) $display("DVAGENT_PROTO cycle=%0d out_valid dropped or data changed '
              'while stalled", dv_cyc);')
            a("      end")
            a(f"      dv_ostall = ({m.out_valid} === 1'b1) && ({m.out_ready} !== 1'b1);")
            a(f"      dv_ohold = {cat};")
        if m.out_valid:
            out_rdy = f" && ({m.out_ready} === 1'b1)" if m.out_ready else ""
            a(f"      if (({m.out_valid} === 1'b1){out_rdy}) begin")
            L.extend(record)
            a("      end")
        elif latency == 0:
            a("      if (dv_cap) begin")
            L.extend(record)
            a("      end")
        else:
            a(f"      if (dv_hist[{latency - 1}]) begin")
            L.extend(record)
            a("      end")
            if latency == 1:
                a("      dv_hist[0] = dv_cap;")
            else:
                a(f"      dv_hist = {{dv_hist[{latency - 2}:0], dv_cap}};")
        a("      if (dv_cap) dv_in_idx = dv_in_idx + 1;")
        a("    end")
        a("  end")
        a("endmodule")

    tb_path = os.path.join(out_dir, "tb.sv")
    with open(tb_path, "w") as f:
        f.write("\n".join(L) + "\n")
    meta = {
        "block": m.name, "top": m.top, "protocol": m.protocol,
        "data_in": [p.name for p in data_in], "data_out": [p.name for p in data_out],
        "out_widths": {p.name: p.width for p in data_out},
        "out_signed": {p.name: p.signed for p in data_out},
        "n_in": n_in, "n_out": n_out, "n_rdy": len(stim.ready),
        "timeout_cycles": timeout if clocked else 0, "latency": latency,
        "seed": stim.seed, "sources": stim.sources,
    }
    with open(os.path.join(out_dir, "tb_meta.json"), "w") as f:
        json.dump(meta, f, indent=2)
    return {"tb": tb_path, **meta}


def _gen_lookup(stim, name):
    """Port generator info (hold flag) attached to the stimulus, if any."""
    return (getattr(stim, "gens", None) or {}).get(name)
