#!/usr/bin/env python3
"""Write LOCK.sha256: the SHA-256 of every file the RTL-editing agent must not change.
loop/loop.py checks this list before every action and refuses to run on any mismatch."""
import hashlib
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
LOCKED = [
    "gate/gate.py", "gate/tbgen.py", "gate/blocks.json", "gate/make_manifest.py",
    "flow/run_flow.py", "flow/sta_report.tcl", "flow/flow_config.json",
    "targets/measure.py", "targets/combine.py", "targets/targets.json", "targets/calibration.json",
    "loop/loop.py", "loop/AGENT_PROMPT.md", "make_lock.py",
]


def main():
    lines = ["# SHA-256 of the locked harness. Generated by make_lock.py. Do not edit."]
    for rel in LOCKED:
        h = hashlib.sha256(open(os.path.join(ROOT, rel), "rb").read()).hexdigest()
        lines.append("%s  %s" % (h, rel))
    open(os.path.join(ROOT, "LOCK.sha256"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("lock digest", hashlib.sha256(("\n".join(lines) + "\n").encode()).hexdigest())


if __name__ == "__main__":
    main()
