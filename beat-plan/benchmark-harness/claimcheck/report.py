"""Render the check results as out/REPORT.md and out/report.json.

Rule for REPORT.md: every line that carries a number also carries a label tag
([MEASURED] [MODELLED] [VENDOR-CLAIM] [NOT-YET]). lint.check_tags() verifies this
after rendering, and the CLI refuses to write a report that fails. The only lines
exempt are the source index between the tagcheck:off and tagcheck:on markers,
which hold titles, dates, hashes and URLs, not quantities.
"""

from __future__ import annotations

import datetime
import json
import os
import subprocess

from . import __version__
from . import fmt
from . import labels as L
from . import lint as LINT
from . import transformer as T
from .registry import HARNESS_ROOT, REPO_ROOT

TAG = L.tag


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _git_commit(repo_root: str) -> str:
    try:
        return subprocess.run(["git", "-C", repo_root, "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, timeout=10).stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def _val(reg, res, nid):
    n = reg.numbers[nid]
    try:
        v = res.value(nid)
    except Exception:
        v = None
    return n, v


def _num(reg, res, nid, with_unit=True) -> str:
    n, v = _val(reg, res, nid)
    if v is None:
        return "none"
    shown = fmt.number(n, v if n.get("formula") else None)
    if n.get("formula") and n.get("value") is None:
        shown = "~" + fmt.sig(v, 3)
    return shown + (" " + n["unit"] if with_unit and n.get("unit") else "")


def _basis(n) -> str:
    lab = n["label"]
    if lab == L.MEASURED:
        return n.get("measured_on", "")
    if lab == L.MODELLED:
        return n.get("basis", "")
    if lab == L.VENDOR_CLAIM:
        return "%s, stated by %s" % (n.get("claim_type"), n.get("stated_by"))
    return "no run"


def _evidence(n) -> str:
    lab = n["label"]
    if lab == L.MEASURED:
        ev = n.get("evidence") or {}
        if ev.get("status") == "not-in-checkout":
            return "reported; evidence not in checkout (%s)" % ev.get("expected", "?")
        return ev.get("status", "?")
    if lab == L.VENDOR_CLAIM:
        return "wording: " + n.get("quote_status", "?")
    if lab == L.MODELLED:
        return "formula registered" if n.get("formula") else "derivation NOT in checkout"
    return "none"


def build(reg, results: dict, runs: list, run_findings: list, run_cmp: list,
          findings: list, lint_rows: list, lint_files: list, now: str = None) -> "tuple[str, dict]":
    res = results["resolver"]
    now = now or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    md = []
    add = md.append

    add("# Forge benchmark and vendor-claim check")
    add("")
    add("Generated by `claimcheck %s` at `%s` from `data/claims.json` (sha256 `%s`), repo commit `%s`. "
        "Regenerate with `python3 -m claimcheck report`." % (__version__, now, reg.sha256()[:16], _git_commit(REPO_ROOT)))
    add("")
    add("**Labels.** %s: a tool printed it during a run, and the evidence is named. "
        "%s: computed by arithmetic or an analytical model, with the formula and assumptions given. "
        "%s: stated by a vendor or publisher and not measured by Forge. %s: no number exists yet."
        % (TAG(L.MEASURED), TAG(L.MODELLED), TAG(L.VENDOR_CLAIM), TAG(L.NOT_YET)))
    add("")

    # ---------------- bottom line
    add("## Bottom line")
    add("")
    lock = reg.numbers.get("forge.beatplan.tokps_474713")
    etched = reg.numbers.get("etched.sohu.server_tokps")
    cmp1 = next((c for c in results["compare"] if c["id"] == "CMP-474713-VS-ETCHED"), None)
    if lock:
        add("- **Forge 474,713 tok/s %s (arithmetic) is not a measurement.** Source: founder brief, 2026-11-27. "
            "Its formula, inputs and conditions are not in this checkout, so the harness cannot reproduce it, "
            "and the registry locks its label to MODELLED." % TAG(L.MODELLED))
    if etched:
        c = etched.get("conditions", {})
        add("- **Etched >500,000 tok/s %s is unverified.** Per Etched: Llama-3 70B, one server of %d Sohu chips, FP8, "
            "%s input / %s output tokens. That wording comes from a search summary, because Etched's page was "
            "unreachable from this session. No independent measurement exists in any reachable source."
            % (TAG(L.VENDOR_CLAIM), c.get("chips"), fmt.plain(c.get("s_in")), fmt.plain(c.get("s_out"))))
    if cmp1:
        add("- **474,713 vs 500,000: %s; %s.** Unknown for the Forge figure: %s. The ratio %s %s is arithmetic only "
            "and says nothing about relative speed."
            % (cmp1["measured"], cmp1["verdict"], ", ".join(cmp1.get("unknown", [])),
               fmt.sig(cmp1["ratio"], 3) if cmp1.get("ratio") is not None else "n/a", TAG(L.MODELLED)))
    n_valid = len([r for r in runs if r.get("_valid") and not r.get("synthetic")])
    add("- **Measured Forge tok/s: none %s.** No FPGA or silicon run exists (Forge site, 2026-11-20), and `runs/` "
        "holds %d usable run records %s." % (TAG(L.NOT_YET), n_valid, TAG(L.MEASURED)))
    q = "forge.harness.tokps_qwen05b_1engine_b1"
    if q in reg.numbers:
        add("- **The only Forge tok/s with a recorded basis** is %s %s for Qwen2.5-0.5B, one engine, batch 1, and it is arithmetic. "
            "It is 1000 / %s %s, from %s %s (simulation, as reported by the site) x %s %s "
            "(met at reduced size, assumed to hold at full size). It is not comparable with Etched's figure "
            "(different model, chip count, precision and metric)."
            % (_num(reg, res, q), TAG(L.MODELLED), _num(reg, res, "forge.site.time_per_token_qwen05b_ms"), TAG(L.MODELLED),
               _num(reg, res, "forge.site.cycles_per_token_qwen05b"), TAG(L.MEASURED),
               _num(reg, res, "forge.site.clock_period_ns"), TAG(L.MEASURED)))
    for va in results["vendor"]:
        io = next(c for c in va["conventions"] if c["convention"] == "input+output")
        oo = next(c for c in va["conventions"] if c["convention"] == "output-only")
        line = ("- **What Etched's figure implies %s:** counting all %s tokens of each request, every Sohu chip must "
                "sustain %s of FP8 compute; counting only the %s output tokens, %s per chip."
                % (TAG(L.MODELLED), fmt.plain(io["counted_tokens_per_request"]), fmt.si(io["chip_flops"], "FLOP/s"),
                   fmt.plain(oo["counted_tokens_per_request"]), fmt.si(oo["chip_flops"], "FLOP/s")))
        if va.get("baseline"):
            b = va["baseline"]
            r_io = next(r for r in b["rows"] if r["convention"] == "input+output")
            r_oo = next(r for r in b["rows"] if r["convention"] == "output-only")
            line += (" Etched's own 8xH100 figure (%s tok/s %s) fits under the H100 dense FP8 peak (%s %s) only "
                     "if input tokens count: %s%% of peak that way versus %s%% counting output only. So input+output "
                     "is the likely convention, and each Sohu chip then needs %sx an H100's dense peak %s."
                     % (fmt.number(reg.numbers[b["claim"]]), TAG(L.VENDOR_CLAIM),
                        fmt.si(b["peak_flops"], "FLOP/s"), TAG(L.MODELLED),
                        fmt.sig(r_io["fraction_of_peak"] * 100), fmt.sig(r_oo["fraction_of_peak"] * 100),
                        fmt.sig(va["chip_flops_vs_peak"]), TAG(L.MODELLED)))
        add(line)
    n_err = len([f for f in findings if f["level"] == "ERROR"])
    n_warn = len([f for f in findings if f["level"] == "WARN"])
    add("- **Registry validation:** %d errors and %d warnings %s (the warnings list honest gaps, see below)." % (n_err, n_warn, TAG(L.MEASURED)))
    add("")

    # ---------------- ledger
    add("## Every number")
    add("")
    add("| ID | What | Value | Label | Basis / measured on | Source | Method | Evidence |")
    add("|---|---|---|---|---|---|---|---|")
    for nid in reg.order:
        n = reg.numbers[nid]
        value = "none" if n["label"] == L.NOT_YET else _num(reg, res, nid)
        add("| `%s` | %s | %s | %s | %s | %s | %s | %s |" % (
            nid, _cell(n.get("what", "")), _cell(value), TAG(n["label"]), _cell(_basis(n)),
            ", ".join("`%s`" % s for s in n.get("source", [])), _cell(n.get("method", "")), _cell(_evidence(n))))
    add("")

    # ---------------- reproduction
    add("## Arithmetic, reproduced")
    add("")
    add("| ID | Formula | Inputs | Stated | Recomputed | Result |")
    add("|---|---|---|---|---|---|")
    for r in results["reproduce"]:
        ins = "; ".join("%s = %s %s (`%s`)" % (i["name"], fmt.sig(i["value"], 4) if isinstance(i["value"], float) and not float(i["value"]).is_integer() else fmt.plain(i["value"]), TAG(i["label"]), i["ref"]) for i in r["inputs"]) or "none registered"
        stated = fmt.plain(r["stated"]) if r.get("stated") is not None else "none"
        rec = fmt.sig(r["recomputed"], 4) if r.get("recomputed") is not None else "none"
        add("| `%s` | %s | %s | %s | %s | %s %s: %s |" % (
            r["id"], "`%s`" % r["formula"] if r.get("formula") else "not in checkout", _cell(ins),
            stated, rec, r["status"], TAG(L.MODELLED), _cell(r.get("detail", ""))))
    add("")

    # ---------------- consistency
    add("## Consistency of the vendor's own figures")
    add("")
    for r in results["consistency"]:
        if r.get("status") == "ERROR":
            add("- `%s`: ERROR, %s" % (r["id"], r.get("detail")))
            continue
        ins = ", ".join("%s = %s %s" % (i["name"], fmt.plain(i["value"]), TAG(i["label"])) for i in r["inputs"])
        labs = sorted({i["label"] for i in r["inputs"]} | {r["target_label"]})
        add("- `%s`: %s (inputs and target: %s)" % (r["id"], r["question"], " ".join(TAG(x) for x in labs)))
        add("  - `%s` with %s gives %s %s %s, which is %s the stated %s %s: **%s**. %s"
            % (r["formula"], ins, fmt.sig(r["implied"], 4), r.get("unit", ""), TAG(L.MODELLED), r["relation"],
               fmt.plain(r["target_value"]), TAG(r["target_label"]), r["status"], r.get("note", "")))
    add("")

    # ---------------- comparisons
    add("## Comparisons")
    add("")
    for c in results["compare"]:
        add("### `%s`" % c["id"])
        add("")
        add(c["question"])
        add("")
        add("- A: %s %s (`%s`)" % (_num(reg, res, c["a"]) if c["label_a"] != L.NOT_YET else "none", TAG(c["label_a"]), c["a"]))
        add("- B: %s %s (`%s`)" % (_num(reg, res, c["b"]) if c["label_b"] != L.NOT_YET else "none", TAG(c["label_b"]), c["b"]))
        add("")
        if c["verdict"] == "NO DATA":
            add("**Verdict:** NO DATA, because one side is %s." % TAG(L.NOT_YET))
            add("")
            continue
        add("| Condition | A | B | State |")
        add("|---|---|---|---|")
        for f in c["fields"]:
            a = "unknown" if f["a"] is None else "%s %s" % (fmt.plain(f["a"]), TAG(c["label_a"]))
            b = "unknown" if f["b"] is None else "%s %s" % (fmt.plain(f["b"]), TAG(c["label_b"]))
            add("| %s | %s | %s | %s |" % (f["field"], _cell(a), _cell(b), f["state"]))
        add("")
        ratio = ("A/B = %s %s, arithmetic only" % (fmt.sig(c["ratio"], 3), TAG(L.MODELLED))) if c.get("ratio") is not None else "no ratio"
        add("**Verdict:** %s; %s. %s." % (c["verdict"], c["measured"], ratio))
        add("")

    # ---------------- vendor analyses
    for va in results["vendor"]:
        add("## Vendor claim analysis: `%s`" % va["claim"])
        add("")
        arch = va["arch_obj"]
        rec = va["arch"]
        add("Claim: %s %s, %s, %s chips, %s input / %s output tokens. Every value below is %s "
            "(analytical model, conventions in `claimcheck/transformer.py`) unless tagged otherwise."
            % (_num(reg, res, va["claim"]), TAG(L.VENDOR_CLAIM), rec["name"], va["chips"],
               fmt.plain(va["s_in"]), fmt.plain(va["s_out"]), TAG(L.MODELLED)))
        add("")
        add("**Architecture inputs** (publisher spec, read from `data/models/%s.json`):" % os.path.basename(rec["name"].lower()))
        add("")
        add("| Field | Value | Label | Cross-check |")
        add("|---|---|---|---|")
        for field, vals, status in T.cross_check(rec):
            add("| %s | %s | %s (spec, %s) | %s: %s |" % (field, fmt.plain(rec["fields"][field]), TAG(L.VENDOR_CLAIM),
                                                     rec["stated_by"], status, _cell(", ".join(sorted(vals)))))
        add("")
        p, rf = va["params"], va["request_flops"]
        add("| Quantity | Value | Label | How |")
        add("|---|---|---|---|")
        add("| Parameters | %s (%s billion) | %s | sum of matrix shapes from the spec |" % (fmt.plain(p["total"]), fmt.sig(p["total"] / 1e9), TAG(L.MODELLED)))
        add("| Positions processed per request | %s | %s | input + output - 1 (the last token is not fed back) |" % (fmt.plain(rf["positions"]), TAG(L.MODELLED)))
        add("| FLOPs per request | %s | %s | linear %s + LM head %s (%s calls) + attention %s |" % (
            fmt.si(rf["total"], "FLOP"), TAG(L.MODELLED), fmt.si(rf["linear"], "FLOP"), fmt.si(rf["lm_head"], "FLOP"),
            fmt.plain(rf["lm_head_calls"]), fmt.si(rf["attention"], "FLOP")))
        add("| Weights streamed per forward pass | %s (%s per chip) | %s | matmul weights incl. LM head; %s |" % (
            fmt.si(va["streamed_weight_bytes"], "B"), fmt.si(va["streamed_weight_bytes"] / va["chips"], "B"), TAG(L.MODELLED),
            _cell(va.get("byte_assumptions", ""))))
        add("| KV cache per token | %s | %s | 2 x layers x KV heads x head dim x bytes |" % (fmt.si(va["kv_bytes_per_token"], "B"), TAG(L.MODELLED)))
        add("| KV cache per full-length request | %s | %s | per token x positions |" % (fmt.si(va["kv_bytes_per_sequence"], "B"), TAG(L.MODELLED)))
        add("")
        add("**Compute the claim requires**, under the two ways of counting tokens (Etched's footnote, as available here, does not say which):")
        add("")
        add("| Tokens counted | Per request | Requests/s | Server FLOP/s | Per-chip FLOP/s | Label |")
        add("|---|---|---|---|---|---|")
        for cv in va["conventions"]:
            add("| %s | %s | %s | %s | %s | %s |" % (cv["convention"], fmt.plain(cv["counted_tokens_per_request"]),
                                                   fmt.sig(cv["requests_per_s"]), fmt.si(cv["server_flops"], "FLOP/s"),
                                                   fmt.si(cv["chip_flops"], "FLOP/s"), TAG(L.MODELLED)))
        add("")
        if va.get("baseline"):
            b = va["baseline"]
            add("**Which counting the vendor's own baseline allows.** `%s` = %s tok/s %s on %s GPUs against %s = %s %s (`%s`):"
                % (b["claim"], fmt.number(reg.numbers[b["claim"]]), TAG(L.VENDOR_CLAIM), b["chips"], b["peak_name"],
                   fmt.si(b["peak_flops"], "FLOP/s"), TAG(L.MODELLED), b["peak_ref"]))
            add("")
            add("| Tokens counted | FLOP/s needed per GPU | Share of peak | Physically possible? | Label |")
            add("|---|---|---|---|---|")
            for r in b["rows"]:
                add("| %s | %s | %s%% | %s | %s |" % (r["convention"], fmt.si(r["chip_flops"], "FLOP/s"),
                                                     fmt.sig(r["fraction_of_peak"] * 100), "yes" if r["feasible"] else "NO",
                                                     TAG(L.MODELLED)))
            add("")
            add("Result %s: %s" % (TAG(L.MODELLED), b["verdict"]))
            if b.get("sparse_peak_flops"):
                r_oo = next(r for r in b["rows"] if r["convention"] == "output-only")
                add("")
                add("Robustness %s: even against NVIDIA's sparse figure of %s %s, output-only counting would need %s%% "
                    "of that peak, so the conclusion does not depend on which peak is used."
                    % (TAG(L.MODELLED), fmt.si(b["sparse_peak_flops"], "FLOP/s"), TAG(L.VENDOR_CLAIM),
                       fmt.sig(r_oo["chip_flops"] / b["sparse_peak_flops"] * 100)))
            add("")
        add("**Weight streaming versus batching** (%s counting). Each forward pass reads every weight once, so the claimed rate "
            "needs the following weight bandwidth per chip for each number of tokens processed per pass:" % va["used_convention"])
        add("")
        add("| Tokens per weight pass | Weight passes/s | Weight bandwidth needed per chip | Label |")
        add("|---|---|---|---|")
        for w in va["weight_passes"]:
            add("| %s | %s | %s | %s |" % (fmt.plain(w["tokens_per_pass"]), fmt.sig(w["weight_passes_per_s"]),
                                         fmt.si(w["bytes_per_s_per_chip"], "B/s"), TAG(L.MODELLED)))
        add("")
        first, last = va["weight_passes"][0], va["weight_passes"][-1]
        add("Reading %s: the figure is an aggregate over many concurrent requests, since at %s token per pass each chip "
            "would need %s of weight bandwidth. It is not the speed one user sees. Per-user speed and concurrency are "
            "not stated in the sources available here." % (TAG(L.MODELLED), fmt.plain(first["tokens_per_pass"]),
                                                       fmt.si(first["bytes_per_s_per_chip"], "B/s")))
        add("")

    # ---------------- runs
    add("## Measured runs")
    add("")
    usable = [r for r in runs if r.get("_valid") and not r.get("synthetic")]
    add("`runs/` holds %d run records, %d of them usable %s (valid, not synthetic). Measured Forge tok/s: %s %s. "
        "A run record is the only way a tok/s figure becomes MEASURED; see `protocol/FPGA_MEASUREMENT_PROTOCOL.md`."
        % (len(runs), len(usable), TAG(L.MEASURED), "none" if not usable else "see below",
           TAG(L.NOT_YET) if not usable else TAG(L.MEASURED)))
    add("")
    if usable:
        from .runs import derive
        add("| Run | Kind | Model | Quantity | Value | Label | Method |")
        add("|---|---|---|---|---|---|---|")
        for rec in usable:
            for d in derive(rec):
                add("| `%s` | %s | %s | %s | %s %s | %s | %s |" % (rec["run_id"], rec["kind"], _cell(rec["model"].get("name")),
                                                             d["name"], fmt.sig(d["value"], 4), d["unit"], TAG(d["label"]), _cell(d["method"])))
        add("")
        for r in run_cmp:
            add("- Run `%s` %s %s %s vs `%s` %s %s: ratio %s %s." % (r["run_id"], r["metric"], fmt.sig(r["run_value"], 4),
                TAG(r["run_label"]), r["claim"], fmt.sig(r["claim_value"], 4), TAG(r["claim_label"]), fmt.sig(r["ratio"], 3), TAG(L.MODELLED)))
        add("")
    for f in run_findings:
        add("- run finding %s `%s` %s: %s" % (f["level"], f["code"], f["id"], _cell(f["message"])))

    # ---------------- lint
    add("## Document lint (tok/s figures)")
    add("")
    errs = [r for r in lint_rows if r["level"] == "ERROR"]
    add("Scanned %d %s %s. Throughput figures found: %d; errors: %d; warnings: %d %s. Files: %s."
        % (len(lint_files), "file" if len(lint_files) == 1 else "files", TAG(L.MEASURED), len(lint_rows), len(errs),
           len([r for r in lint_rows if r["level"] == "WARN"]), TAG(L.MEASURED),
           ", ".join("`%s`" % f for f in lint_files) or "none"))
    add("")
    if lint_rows:
        add("Figures are quoted from the scanned files, with the unit in its own column. The Registry column gives the label "
            "the figure should carry.")
        add("")
        add("| Where | Quoted figure | Unit | Label words near it | Registry | Result |")
        add("|---|---|---|---|---|---|")
        for r in lint_rows:
            reg_s = ("`%s` %s" % (r["registry"], TAG(r["registry_label"]))) if r["registry"] else "not registered"
            words = ", ".join(w.lower() for w in r["asserted"]) or "none"
            add("| `%s` | `%s` | `%s` | %s | %s | %s `%s` |" % (r["where"], r["figure"], r["unit"], words,
                                                              reg_s, r["level"], r["code"]))
        add("")

    # ---------------- findings / gaps
    add("## Open gaps (validator warnings)")
    add("")
    for f in findings:
        if f["level"] in ("ERROR", "WARN"):
            label = reg.label_of(f["id"])
            add("- %s `%s` `%s`%s: %s" % (f["level"], f["code"], f["id"], (" " + TAG(label)) if label else "", _cell(f["message"])))
    add("")
    add("## Needed to finish the check")
    add("")
    add("- `BEAT_PLAN.md` and `beat-plan/strategy/`: the formula, inputs and conditions behind 474,713 tok/s %s (model, chips, clock, "
        "precision, input/output lengths, batch, token counting). Put them in `data/claims.json` (`formula` and `inputs`) and the "
        "harness will recompute the figure and check it against Etched's conditions." % TAG(L.MODELLED))
    add("- Forge's evidence files (proof logs, gate, timing and power reports, perplexity logs) with sha256, so that site figures "
        "move from reported to re-verified.")
    add("- A saved copy of Etched's announcement page under `data/sources/`, so the search-summary wording of the >500,000 tok/s "
        "%s claim can be checked word for word." % TAG(L.VENDOR_CLAIM))
    add("- FPGA run records under `runs/`, following `protocol/FPGA_MEASUREMENT_PROTOCOL.md`. Until one exists, Forge has no measured tok/s %s." % TAG(L.NOT_YET))
    add("- The SKILL.md files for forge-benchmark-rerun, forge-vendor-claim-check and forge-fpga-measurement (not in this checkout). "
        "Reconcile them with `protocol/`.")
    add("")

    # ---------------- sources
    add("## Sources")
    add("")
    add("<!-- tagcheck:off -->")
    add("| ID | Quality | What | Where |")
    add("|---|---|---|---|")
    for sid, s in reg.sources.items():
        where = s.get("url") or s.get("path") or s.get("package") or s.get("location") or ""
        if not where and s.get("result_urls"):
            where = "results include " + ", ".join(s["result_urls"][:2])
        extra = []
        if s.get("sha256"):
            extra.append("sha256 `%s`" % s["sha256"][:16])
        if s.get("wheel_sha256"):
            extra.append("wheel sha256 `%s` (matches PyPI)" % s["wheel_sha256"][:16])
        if s.get("reachable_from_session") is False:
            extra.append("NOT READ: unreachable from this session")
        what = s.get("title") or ("web search for: %s (%s)" % (s.get("query", ""), s.get("date", "")))
        add("| `%s` | %s | %s | %s %s |" % (sid, s.get("quality"), _cell(what), _cell(where), "; ".join(extra)))
    add("<!-- tagcheck:on -->")
    add("")
    add("Quoted wording, with the label of the number it supports:")
    add("")
    for nid in reg.order:
        n = reg.numbers[nid]
        if n.get("quote"):
            add("- `%s` %s (%s): \"%s\"" % (nid, TAG(n["label"]), n.get("quote_status"), n["quote"]))
    for q in reg.sources.get("SRC-BRIEF", {}).get("quotes", []):
        add("- `SRC-BRIEF` %s %s (founder brief): \"%s\"" % (TAG(L.MODELLED), TAG(L.VENDOR_CLAIM), q))
    add("")

    text = "\n".join(md) + "\n"
    data = _json_payload(reg, results, runs, run_findings, run_cmp, findings, lint_rows, lint_files, now)
    return text, data


def tag_problems(text: str, name: str = "REPORT.md") -> list:
    """check_tags() on the report, skipping the declared tagcheck:off sections."""
    kept, skip = [], False
    for line in text.splitlines():
        if line.strip() == "<!-- tagcheck:off -->":
            skip = True
            kept.append("")
            continue
        if line.strip() == "<!-- tagcheck:on -->":
            skip = False
            kept.append("")
            continue
        kept.append("" if skip else line)
    return LINT.check_tags("\n".join(kept), name)


def _json_payload(reg, results, runs, run_findings, run_cmp, findings, lint_rows, lint_files, now) -> dict:
    res = results["resolver"]
    numbers = []
    for nid in reg.order:
        n = dict(reg.numbers[nid])
        try:
            n["resolved_value"] = res.value(nid) if n["label"] != L.NOT_YET else None
        except Exception:
            n["resolved_value"] = None
        numbers.append(n)
    vendor = []
    for va in results["vendor"]:
        v = {k: va[k] for k in va if k not in ("arch_obj",)}
        v["label"] = L.MODELLED
        vendor.append(v)
    clean_runs = [{k: v for k, v in r.items()} for r in runs]
    return {
        "schema": "forge-claimcheck-report/1", "generated_utc": now, "tool_version": __version__,
        "registry_sha256": reg.sha256(), "numbers": numbers,
        "reproduce": results["reproduce"], "consistency": results["consistency"], "compare": results["compare"],
        "vendor_analyses": vendor, "runs": clean_runs, "run_findings": run_findings, "run_vs_claims": run_cmp,
        "validator_findings": findings, "lint": {"files": lint_files, "rows": lint_rows},
        "label_rule": "computed values are MODELLED; MEASURED requires a run with evidence; VENDOR-CLAIM is never verified by this harness",
    }


def write(out_dir: str, text: str, data: dict) -> "tuple[str, str]":
    os.makedirs(out_dir, exist_ok=True)
    md_path, js_path = os.path.join(out_dir, "REPORT.md"), os.path.join(out_dir, "report.json")
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(text)
    with open(js_path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2, sort_keys=False, default=str)
        fh.write("\n")
    return md_path, js_path


